// Interface text in French and English. `en` is typed from `fr`, so a missing or extra key fails the build.

export type Lang = 'fr' | 'en';
export const LANG_COOKIE = 'aw_lang';
export const locales: Record<Lang, string> = { fr: 'fr-FR', en: 'en-US' };

export function isLang(value: unknown): value is Lang {
  return value === 'fr' || value === 'en';
}

/** A saved choice wins; otherwise French for French-language browsers and English for everyone else. */
export function pickLang(saved?: string | null, acceptLanguage?: string | null): Lang {
  if (isLang(saved)) return saved;
  const ranked = (acceptLanguage || '')
    .split(',')
    .map((part, index) => {
      const [tag, ...params] = part.trim().toLowerCase().split(';');
      const q = Number(params.find((p) => p.trim().startsWith('q='))?.split('=')[1] ?? 1);
      return { tag, q: Number.isFinite(q) ? q : 0, index };
    })
    .filter((entry) => entry.tag && entry.q > 0)
    .sort((a, b) => b.q - a.q || a.index - b.index);
  for (const { tag } of ranked) {
    if (tag.startsWith('fr')) return 'fr';
    if (tag.startsWith('en')) return 'en';
  }
  return 'en';
}

export function langFromRequest(request: Request): Lang {
  const saved = request.headers
    .get('cookie')
    ?.split(';')
    .map((part) => part.trim().split('='))
    .find(([name]) => name === LANG_COOKIE)?.[1];
  return pickLang(saved, request.headers.get('accept-language'));
}

